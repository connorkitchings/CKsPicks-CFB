/**
 * Pure helpers for build-team-logos.mjs (no network, no filesystem except
 * where a function says so), so they can be unit-tested with synthetic data.
 */
import crypto from "node:crypto";

export const SIZES = { sm: 96, lg: 256 };
export const THEMES = ["light", "dark"];

const ESPN_LIGHT = (id) => `https://a.espncdn.com/i/teamlogos/ncaa/500/${id}.png`;

export function espnDarkUrl(lightUrl) {
  return lightUrl.includes("/500/") ? lightUrl.replace("/500/", "/500-dark/") : null;
}

/**
 * Normalize the CFBD `/teams/fbs` response into
 * `[{ id, school, abbreviation, color, altColor, light, dark, usedFallback }]`.
 * A team without a usable `logos[0]` falls back to the ESPN CDN URL for its id.
 * Display metadata (abbreviation, colors) is kept as published, or null when absent
 * or malformed; it never decides conference or any other data.
 */
export function parseTeams(rows) {
  if (!Array.isArray(rows)) throw new Error("CFBD response is not an array");
  const teams = [];
  for (const row of rows) {
    const id = Number(row?.id);
    const school = typeof row?.school === "string" ? row.school.trim() : "";
    if (!Number.isInteger(id) || id <= 0 || !school) continue;
    const logos = Array.isArray(row.logos) ? row.logos.filter((u) => typeof u === "string") : [];
    const first = logos.find((u) => /^https:\/\//.test(u));
    const light = first ?? ESPN_LIGHT(id);
    const darkFromList = logos.find((u) => /^https:\/\//.test(u) && u !== light && /dark/.test(u));
    teams.push({
      id,
      school,
      abbreviation: cleanAbbreviation(row.abbreviation),
      color: cleanColor(row.color),
      altColor: cleanColor(row.alternateColor ?? row.alternate_color ?? row.alt_color),
      light,
      dark: darkFromList ?? espnDarkUrl(light),
      usedFallback: !first,
    });
  }
  const seen = new Set();
  return teams
    .filter((t) => (seen.has(t.id) ? false : (seen.add(t.id), true)))
    .sort((a, b) => a.id - b.id);
}

const HEX_COLOR = /^#[0-9a-fA-F]{6}$/;

export function cleanColor(value) {
  const text = typeof value === "string" ? value.trim() : "";
  return HEX_COLOR.test(text) ? text.toLowerCase() : null;
}

export function cleanAbbreviation(value) {
  const text = typeof value === "string" ? value.trim() : "";
  return text && text.length <= 8 ? text.toUpperCase() : null;
}

export function sha256(buffer) {
  return crypto.createHash("sha256").update(buffer).digest("hex");
}

/** Relative path under public/logos/v2 for one asset. */
export function assetPath(size, theme, id) {
  return `${size}/${theme}/${id}.webp`;
}

export function buildManifest(entries, retrieved) {
  return {
    version: 2,
    retrieved,
    sizes: SIZES,
    teams: Object.fromEntries(
      entries
        .slice()
        .sort((a, b) => a.id - b.id)
        .map((e) => [
          String(e.id),
          {
            school: e.school,
            sources: e.sources,
            darkFallbackToLight: e.darkFallbackToLight,
            files: e.files,
          },
        ]),
    ),
  };
}

/** Source for web/src/lib/team-logos.generated.ts. */
export function buildGeneratedTs(entries) {
  const sorted = entries.slice().sort((a, b) => a.school.localeCompare(b.school));
  const lines = sorted.map((e) => `  ${JSON.stringify(e.school)}: ${e.id},`);
  const display = sorted.map(
    (e) =>
      `  ${JSON.stringify(e.school)}: { abbr: ${JSON.stringify(e.abbreviation ?? null)}, color: ${JSON.stringify(e.color ?? null)}, altColor: ${JSON.stringify(e.altColor ?? null)} },`,
  );
  return [
    "// GENERATED by scripts/build-team-logos.mjs. Do not edit by hand.",
    "// School name (CFBD) -> team id; files live at /logos/v2/<size>/<theme>/<id>.webp.",
    "export const LOGO_IDS: Record<string, number> = {",
    ...lines,
    "};",
    "",
    "// School name (CFBD) -> display metadata (abbreviation, primary and alternate color).",
    "// Display only: conference and every other fact come from published release data.",
    "export type TeamDisplay = { abbr: string | null; color: string | null; altColor: string | null };",
    "export const TEAM_DISPLAY: Record<string, TeamDisplay> = {",
    ...display,
    "};",
    "",
  ].join("\n");
}

/**
 * The metadata-only refresh must not change which teams or ids the logo set has:
 * returns the problems (empty when the fetched teams match the manifest exactly).
 */
export function manifestMismatches(teams, manifest) {
  const known = Object.fromEntries(
    Object.entries(manifest.teams ?? {}).map(([id, team]) => [Number(id), team.school]),
  );
  const fetched = Object.fromEntries(teams.map((t) => [t.id, t.school]));
  const problems = [];
  for (const [id, school] of Object.entries(fetched)) {
    if (known[id] !== school) problems.push(`${school} (${id}) differs from the manifest`);
  }
  for (const [id, school] of Object.entries(known)) {
    if (fetched[id] !== school) problems.push(`${school} (${id}) is absent from the response`);
  }
  return problems;
}
